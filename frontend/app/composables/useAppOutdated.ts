/**
 * Признак того, что вкладка работает на устаревшей сборке.
 *
 * Приложение живёт в айфрейме Битрикса, и жёсткая перезагрузка внешней
 * страницы содержимое фрейма НЕ обновляет. Вкладка может неделями исполнять
 * код, которого на сервере давно нет (инцидент 31.08.2026). Сервер такие
 * запросы отклоняет — 409 с кодом app_version_mismatch, — но человеку от
 * кода ошибки пользы мало: ему нужно понять, что делать.
 *
 * Состояние модульного уровня, а не в сторе, намеренно: флаг взводится из
 * перехватчика ошибок общего http-клиента, и тащить туда стор ради одного
 * булева значения незачем. Обратного перехода нет — устаревшая вкладка сама
 * собой новой не станет, лечится только перезагрузкой.
 */
const isOutdated = ref(false)

export function useAppOutdated() {
  /** Взводится перехватчиком $api при 409 app_version_mismatch. */
  const markOutdated = () => {
    isOutdated.value = true
  }

  /**
   * Перезагружает вкладку.
   *
   * Именно по кнопке, а не автоматически: в форме списания может быть
   * несохранённый ввод, и молча его потерять хуже, чем показать баннер.
   */
  const reloadApp = () => {
    if (typeof window !== 'undefined') {
      window.location.reload()
    }
  }

  return { isOutdated: readonly(isOutdated), markOutdated, reloadApp }
}
