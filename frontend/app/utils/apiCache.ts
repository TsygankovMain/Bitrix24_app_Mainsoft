/**
 * Общий приём для эндпоинтов с серверным кэшем, которые умеют его
 * принудительно обходить по query-параметру (см. getProjectBoardMeta в
 * frontend/app/stores/api.ts — первый и до этой правки единственный такой
 * эндпоинт).
 *
 * Блокер 2 финального ревью (2026-07-28): getProjectBoard/getHomepagePortfolio
 * принимали forceRefresh, но им управлялся только браузерный (localStorage)
 * кэш в withBrowserCache — сам HTTP-запрос всегда уходил без параметров, и
 * его получал СЕРВЕРНЫЙ кэш бэкенда. Тот кэш — per-процессный (за
 * балансировщиком несколько процессов, у каждого своя память): сброс,
 * который делает create_project в процессе, обработавшем запрос, не долетает
 * до другого процесса, который может обслужить следующий запрос доски или
 * главного экрана. Симптом: «создал и не увидел», примерно через раз.
 *
 * ?refresh=1 сообщает бэкенду, что нужно обойти его кэш и пересчитать ответ
 * заново (бэкенд разбирает параметр сверкой с множеством "истинных" строк —
 * см. backends/python/api/main/views.py, get_project_board_meta), а не
 * int()/bool() — сам параметр всегда пишем как '1', подстраиваясь под уже
 * принятый бэкендом контракт.
 */
export function withRefreshParam(url: string, forceRefresh: boolean): string {
  if (!forceRefresh) return url
  const separator = url.includes('?') ? '&' : '?'
  return `${url}${separator}refresh=1`
}
