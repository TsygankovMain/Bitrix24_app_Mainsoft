/**
 * БДДС по проектам (вариант A редизайна, пункт «Финансы»).
 *
 * Роль флага СМЕНИЛАСЬ. Пока функции не было, он один решал, показывать ли
 * пункт меню рабочим, и в этом докстринге было честно написано, что он
 * ничего не защищает: бэкенд о подписке не знал. Теперь у функции есть
 * экраны (app/pages/finance/bdds/**) и серверная проверка подписки:
 * GET /api/features отдаёт состояние портала (on | trial | off), а все
 * ручки БДДС закрыты декоратором @feature_required('bdds') — В ТОМ ЧИСЛЕ
 * на чтении, потому что у функции нет документа, который клиент уже
 * создал и обязан видеть дальше (этим она отличается от «Счёта и акта»).
 *
 * Поэтому флаг стоит в true и работает как АВАРИЙНЫЙ ВЫКЛЮЧАТЕЛЬ: закрыть
 * точку входа на всех порталах разом он может, открыть её вопреки серверу —
 * нет (см. resolveBddsAccess в app/utils/bddsFeature.ts, там же тесты на
 * оба направления).
 *
 * Ставить false стоит ровно в одном случае: экран сломан в проде, а откат
 * выката унёс бы вместе с ним не связанные исправления. Обычное «отключить
 * клиенту» делается на сервере — management-командой над PortalFeature
 * (`billing_feature --code bdds --state off`), и тогда человек видит замок
 * и заглушку, а не пропавший пункт меню. Описания функций, которые видит
 * человек, лежат в app/utils/paidFeatures.ts.
 */
export const FINANCE_BDDS_ENABLED = true

