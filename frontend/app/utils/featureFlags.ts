/**
 * Форма «Создать проект» (docs/superpowers/specs/2026-07-28-create-project-button-design.md).
 *
 * Была выключена 29.07.2026 по итогам первого дня в проде — сценарий
 * «компании нет в базе, завожу новую» оказался непригоден. Причина, по
 * которой дефект дожил до прода: вся логика формы жила внутри .vue, а
 * node:test через tsx не резолвит .vue — ревью проверяло чистые функции и
 * не могло пройти сам экран. Хотфикс (.superpowers/sdd/2026-07-28-create-project-button/
 * hotfix-new-company-brief.md, отчёт — hotfix-new-company-report.md там же)
 * вынес решения в чистые функции frontend/app/utils/companySearch.ts и
 * покрыл их тестами, поэтому включена обратно тем же днём. Три дефекта и их
 * фикс:
 *  1. Введённое название компании не было видно на экране после закрытия
 *     списка — SearchableSelect.vue::displayLabel показывал "Компания не
 *     выбрана" всегда, когда компания не выбрана ИЗ СПИСКА, а у новой
 *     компании выбирать нечего. Текст при этом был жив в form.company_name,
 *     человек считал ввод потерянным. Фикс: pendingCompanyDisplayLabel +
 *     новый проп SearchableSelect pendingCompanyName.
 *  2. Не было действия «создать компанию с этим названием»: при пустом
 *     результате поиска показывалась неактивная надпись «Ничего не
 *     найдено», хотя подсказка под полем обещала обратное. Фикс:
 *     shouldOfferCompanyCreation + companyCreationActionLabel, событие
 *     SearchableSelect create-requested.
 *  3. Escape в строке поиска закрывал не список, а всё модальное окно —
 *     обработчик гасил список, но не останавливал событие, и его следом
 *     ловил сам диалог (B24Modal, Reka UI DismissableLayer). Фикс:
 *     document-слушатель с {capture: true} + условный stopPropagation.
 *
 * Связка company_id/company_name (Важное 3 финального ревью задачи 8, см.
 * докстринг companyFieldsForQuery в companySearch.ts) при этой правке не
 * тронута — новый путь создания компании тоже пишет оба поля одной
 * операцией через companyFieldsForQuery.
 */
export const CREATE_PROJECT_BUTTON_ENABLED = true

/**
 * Какой экран открывается во вкладке задачи (placement TASK_VIEW_TAB).
 *
 * Экранов учёта часов в приложении три, и переезд на Bitrix24 UI Kit идёт
 * постепенно:
 *  - '/embedded' — рабочий экран. Собственная вёрстка, ноль компонентов UI Kit,
 *    но умеет всё: отражение часов, правку, удаление, разделение записи,
 *    фильтры, ИНН и привязку к проекту;
 *  - '/task' — тот же учёт на компонентах UI Kit. Дерево, правка и отражение
 *    часов уже перенесены; удаление, разделение и фильтры — ещё нет.
 *
 * ПЕРЕКЛЮЧЕНИЕ И ОТКАТ. В проде placement привязан напрямую к /embedded, и
 * корень приложения не открывается вовсе — значит одной этой константы для
 * переключения НЕ достаточно, нужен ре-бинд placement'а на новый маршрут.
 * Зато и откат мгновенный: обратный ре-бинд placement'а на /embedded
 * возвращает прежний экран без пересборки и передеплоя.
 *
 * Экран /embedded при переносе не трогается ни одной строкой (у него свои
 * компоненты — TaskGroupComponent; у /task свои — TaskNode/TaskItemRow),
 * поэтому откат не требует ничего восстанавливать.
 */
export const TASK_TAB_ROUTE: '/embedded' | '/task' = '/embedded'
