/**
 * Чистая логика состояния модалки «Создать проект», вынесенная из
 * CreateProjectModal.vue: SFC в этом проекте не покрыт юнит-тестами
 * (node:test через tsx не резолвит .vue), а решения ниже — как раз та
 * логика, которую фикс-раунд ревью задачи 8 явно попросил проверить тестом
 * (см. .superpowers/sdd/2026-07-28-create-project-button/task-8-report.md,
 * «Фикс-раунд»).
 */
import type { ProjectCreationResult } from '~/types/project-creation'

/**
 * Находка 1: безусловный сброс формы при каждом открытии терял данные при
 * частичном сбое. Пример: компания создалась, группа — нет; на экране
 * частичный результат и кнопка «Повторить»; сотрудник случайно закрыл окно
 * (оно закрываемо сразу после ответа — см. :close="!submitting" в
 * компоненте) и открыл заново. Название, правки дат, бюджет часов,
 * переопределённая ставка, признак поддержки и прогресс по шагам стирались,
 * хотя идемпотентность бэкенда требует того же имени, чтобы не плодить
 * дубли, — восстанавливать введённое пришлось бы вручную.
 *
 * Сброс допустим только когда предыдущая попытка ЗАВЕРШЕНА:
 * - результата ещё не было (null — свежее открытие, терять нечего);
 * - последний результат успешен (done === true — та же семантика, что и в
 *   ProjectCreationResult.done: «карточка не в состоянии ошибки», это верно
 *   и когда карточка осознанно skipped из-за ненастроенного смарт-процесса —
 *   нормальный успешный исход, а не повод восстанавливать форму).
 *
 * Во всех остальных случаях (done === false: ошибка шага, неоднозначность,
 * не хватает обязательных полей, занятый лок создания) — предыдущая попытка
 * оборвана на полпути, и открытие модалки обязано вернуть сотрудника ровно
 * туда, где он был, а не заставлять вводить всё заново.
 */
export function shouldResetFormOnOpen(previousResult: ProjectCreationResult | null): boolean {
  return previousResult === null || previousResult.done === true
}

/**
 * Находка 2: поле выбора юрлица и подсказка о том, что оно обязательно,
 * жили за одним условием — клиентским `legalEntities.length > 1`. Бэкенд же
 * решает необходимость поля независимо и заново на каждой отправке
 * (project_creation_defaults.resolve_project_fields). Если список юрлиц на
 * клиенте не догрузился на портале, где их на самом деле несколько, клиент
 * решает, что поле не нужно, пропускает его в отправке, а бэкенд отвечает
 * missing_fields с our_legal_entity_id — но раз клиентское условие остаётся
 * false, ни поле, ни подсказка не показываются вообще: все три шага
 * приходят "пропущено" без единого объяснения.
 *
 * Показываем блок, если поле нужно по любой из двух независимых оценок.
 */
export function shouldShowLegalEntityBlock(clientNeedsChoice: boolean, missingFields: string[]): boolean {
  return clientNeedsChoice || (missingFields ?? []).includes('our_legal_entity_id')
}

/**
 * Показать блок — не значит сделать его заполнимым: если список юрлиц на
 * клиенте не догрузился (см. MyCompaniesResult.failed) или устарел, поле
 * выбора окажется пустым и сотрудник всё равно застрянет, просто с другим
 * симптомом. Раз бэкенд настаивает на юрлице, а у клиента 0 или 1 запись —
 * этой записи недостаточно, чтобы объяснить бэкендовское решение, значит
 * список, вероятнее всего, не отражает реальность портала. Перезагрузка
 * дешева (список кэшируется на бэкенде 6 часов) и часто чинит ситуацию без
 * того, чтобы сотрудник закрывал и открывал окно заново вручную.
 */
export function shouldRefetchLegalEntities(missingFields: string[], legalEntitiesCount: number): boolean {
  return (missingFields ?? []).includes('our_legal_entity_id') && legalEntitiesCount <= 1
}

/** Поля из missing_fields, у которых уже есть выделенное место на форме —
 * подсказка рядом с самим полем (см. resolve_project_fields — сегодня это
 * ровно четыре ключа). Если бэкенд когда-нибудь начнёт присылать
 * missing_fields с ключом без своего слота на экране — тот же класс бага,
 * что и находка 2, просто для другого поля. */
const SLOTTED_MISSING_FIELDS = ['project_name', 'company', 'our_legal_entity_id', 'hourly_rate']

/** Запасной путь на случай будущего поля без своего слота: то, что не
 * покрыто ни одной точечной подсказкой на форме, показываем одним общим
 * сообщением — лучше невзрачное объяснение, чем молчаливый отказ. */
export function unslottedMissingFields(missingFields: string[]): string[] {
  return (missingFields ?? []).filter(field => !SLOTTED_MISSING_FIELDS.includes(field))
}

const MISSING_FIELD_LABELS: Record<string, string> = {
  project_name: 'название проекта',
  company: 'компания',
  our_legal_entity_id: 'юрлицо',
  hourly_rate: 'ставка'
}

/** Человеко-читаемая подпись поля для общего сообщения о недостающих
 * данных. Неизвестный ключ показываем как есть — сырой код поля лучше, чем
 * пустое место в сообщении. */
export function missingFieldLabel(field: string): string {
  return MISSING_FIELD_LABELS[field] ?? field
}
