/**
 * ИНН — чистая проверка формы: длина и состав символов. Зеркалит
 * backends/python/api/main/inn_validation.py (см. её докстринг про то же
 * решение, сверено построчно, не по памяти) — тот же порядок проверок
 * (пусто -> только ASCII-цифры -> длина) и тот же текст ошибок, НЕ строже.
 * Обе стороны обязаны совпадать: бэкенд не доверяет фронту (форму можно
 * обойти прямым POST на /api/project-board/create), а фронт не должен быть
 * строже бэкенда — иначе сотрудник получил бы отказ на форме там, где
 * сервер данные бы принял.
 *
 * Что проверяется и почему:
 * - Длина — 10 цифр для юридического лица, 12 для ИП/физлица (INN_LENGTHS,
 *   тот же стандарт ФНС). Без этого опечатка в один-два символа заводит в
 *   CRM клиента реквизит, который потом не найти по настоящему ИНН.
 * - Состав символов — ТОЛЬКО обычные ASCII-цифры. Не про опечатки: у
 *   арабских, тайских и деванагари цифр тоже "выглядят цифрами", и без
 *   явной проверки набора символов такая строка казалась бы валидным ИНН —
 *   но обычный поиск по ИНН на портале (RQ_INN=<ascii-строка>) такую
 *   запись не находит, символы другие при том же числовом значении. Это
 *   защита данных клиента, а не строгость ради строгости (см. тесты на
 *   юникод-цифры в tests/innValidation.test.ts).
 *
 * Что НЕ проверяется и почему — контрольная сумма (стандартная арифметика
 * ФНС). Решение заказчика (см. .superpowers/sdd/2026-07-28-create-project-button/
 * inn-trim-report.md): сам Битрикс в своём интерфейсе создания реквизита
 * контрольную сумму ИНН не проверяет — принимает любые 10/12 ASCII-цифр.
 * Проверять строже платформы, в которую эти же данные всё равно попадают,
 * смысла не имеет.
 */

/** Тот же стандарт ФНС, что и INN_LENGTHS в inn_validation.py — не
 * импортируется оттуда (это разные рантаймы), значение (10, 12) меняться
 * не должно. */
export const INN_LENGTHS: readonly number[] = [10, 12]

export const ERROR_BLANK = 'ИНН не указан.'
export const ERROR_NOT_DIGITS = 'ИНН должен состоять только из цифр.'
export const ERROR_LENGTH = 'ИНН должен содержать 10 цифр (юридическое лицо) или 12 цифр (ИП/физлицо).'

/** Строка без пробелов по краям. `null`/`undefined` -> "". Состав символов
 * не проверяет — для этого validateInn ниже. Принимает `unknown`, а не
 * `string`: поле формы всегда строка из <input>, но функция всё равно не
 * должна падать на произвольном значении (см. validateInn). */
export function normalizeInn(value: unknown): string {
  if (value === null || value === undefined) {
    return ''
  }
  return String(value).trim()
}

/** Явный список ASCII-цифр через regex `[0-9]` — не полагаемся на то, что
 * рантайм умеет отличать ASCII-цифры от юникод-цифр "сам": в отличие от
 * Python str.isdigit() (истинно для арабских/тайских/деванагари цифр),
 * regex `[0-9]` в JS и так ASCII-only по спецификации ECMA-262 — но явный
 * набор здесь оставлен нарочно, тем же приёмом, что и в inn_validation.py
 * (_is_ascii_digits, frozenset ASCII-цифр), чтобы обе стороны читались
 * одинаково и не разошлись, если один из рантаймов когда-нибудь изменит
 * трактовку \d (например, с флагом /u и \p{Nd}). */
const ASCII_DIGITS_RE = /^[0-9]+$/

function isAsciiDigits(text: string): boolean {
  return text.length > 0 && ASCII_DIGITS_RE.test(text)
}

/**
 * `null`, если ИНН валиден по форме; иначе — текст причины на русском,
 * готовый для прямого показа сотруднику.
 *
 * Проверяется только форма: пусто -> только ASCII-цифры -> длина.
 * Контрольная сумма сознательно не считается (см. докстринг модуля).
 * Порядок осознанный: сообщение указывает на первую реальную проблему
 * ввода, а не смешивает, например, "есть буква" и "неверная длина" в одном
 * тексте — тот же порядок, что и в validate_inn на бэкенде.
 *
 * Принимает `unknown`, а не `string`, и никогда не бросает исключение —
 * v-model всегда даёт строку, но защита от произвольного мусора ничего не
 * стоит и держит функцию симметричной бэкендной (validate_inn там тоже
 * никогда не падает на мусоре из тела запроса).
 */
export function validateInn(value: unknown): string | null {
  const text = normalizeInn(value)
  if (!text) {
    return ERROR_BLANK
  }
  if (!isAsciiDigits(text)) {
    return ERROR_NOT_DIGITS
  }
  if (!INN_LENGTHS.includes(text.length)) {
    return ERROR_LENGTH
  }
  return null
}

export function isValidInn(value: unknown): boolean {
  return validateInn(value) === null
}
