"""ИНН — чистая проверка формы: длина и состав символов. Контрольная сумма —
сознательно НЕ проверяется (почему — см. ниже).

Без Django и без сети — как project_creation_defaults.py по соседству (см.
докстринг того модуля про то же требование): та же арифметика дублируется
на фронте (frontend/app/utils/, задача идёт отдельно после этой), и обе
стороны обязаны проверяться одинаково, без моков сети или Django. Бэкендная
копия обязательна НЕЗАВИСИМО от фронтовой — фронт можно обойти прямым POST
на create_project_board (см. докстринг ensure_company в
project_creation_service.py).

Что проверяется и почему:
- Длина — 10 цифр для юридического лица, 12 для ИП/физлица (INN_LENGTHS,
  тот же стандарт ФНС, что и в company_search_service.py). Без этого
  опечатка в один-два символа заводит в CRM клиента реквизит, который потом
  не найти по настоящему ИНН.
- Состав символов — ТОЛЬКО обычные ASCII-цифры (см. _is_ascii_digits ниже).
  Это главная ценность модуля, не формальность и не про опечатки: у
  арабских, тайских и деванагари цифр `str.isdigit()` тоже истинно, а
  `int(...)` молча преобразует их в нужное число БЕЗ исключения (например,
  тайская запись "๗๗๐๗๐๘๓๘๙๓" и деванагари "७७०७०८३८९३" обе дают
  int(...) == 7707083893 — ни разу не бросив ValueError). Без явной проверки
  набора символов такая строка выглядела бы валидным ИНН и ушла бы в CRM
  клиента как реквизит — но обычный поиск по ИНН (crm.requisite.list,
  RQ_INN=<ascii-строка>) такую запись не находит: символы другие, хотя
  число то же самое. Это защита данных клиента, а не строгость проверки
  ради строгости.

Что НЕ проверяется и почему — контрольная сумма (стандартная арифметика ФНС:
одна контрольная цифра для юрлица, две для ИП). Раньше считалась, убрана
намеренно (задача на вычитание, см. inn-trim-report.md): сам Битрикс в своём
интерфейсе создания реквизита контрольную сумму ИНН не проверяет — принимает
любые 10/12 ASCII-цифр. Проверять строже, чем платформа, в которую эти же
данные всё равно попадают, смысла не имеет: сотрудник получил бы отказ там,
где сам Битрикс ИНН бы принял, а от порчи данных (в отличие от нечитаемых
юникод-цифр выше) это не защищает — битый по контрольной сумме, но честный
ASCII-номер по-прежнему нормально ищется и хранится.
"""
from typing import Any, Optional, Tuple

# Тот же набор длин, что и INN_LENGTHS в company_search_service.py — не
# импортируется оттуда намеренно: тот модуль тянет Django (cache.cache), а
# этот обязан остаться проверяемым без Django (см. докстринг выше). Две
# копии одной константы — сознательный выбор в пользу независимости модулей,
# а не забытый дубль: значение (10, 12) — стандарт ФНС, меняться не должно.
INN_LENGTHS: Tuple[int, int] = (10, 12)

_ASCII_DIGITS = frozenset("0123456789")

ERROR_BLANK = "ИНН не указан."
ERROR_NOT_DIGITS = "ИНН должен состоять только из цифр."
ERROR_LENGTH = "ИНН должен содержать 10 цифр (юридическое лицо) или 12 цифр (ИП/физлицо)."


def normalize_inn(value: Any) -> str:
    """Строка без пробелов по краям. `None` -> "". Состав символов не проверяет —
    для этого validate_inn ниже."""
    if value is None:
        return ""
    return str(value).strip()


def _is_ascii_digits(text: str) -> bool:
    """`text.isdigit()` — ловушка: True для символов вида "⁴" (верхний индекс)
    и арабских/тайских/деванагари цифр, а `int(...)` половину из них молча
    преобразует в обычное число, не бросая исключение (см. докстринг модуля
    выше — тайская и деванагари запись того же числа проверены прогоном), а
    другую половину (например, "⁴") роняет необработанным ValueError. Наивная
    проверка text.isdigit() пропустила бы обе разновидности дальше как
    "цифры" (см. tests_inn_validation.test_unicode_digit_lookalikes_are_
    rejected_not_crash, где оба случая воспроизведены). Явный набор
    ASCII-цифр — единственная проверка здесь, которой можно доверять."""
    return bool(text) and all(ch in _ASCII_DIGITS for ch in text)


def validate_inn(value: Any) -> Optional[str]:
    """`None`, если ИНН валиден по форме; иначе — текст причины на русском
    (готов для прямого показа сотруднику).

    Проверяется только форма: пусто -> только ASCII-цифры -> длина.
    Контрольная сумма сознательно не считается (см. докстринг модуля).
    Порядок всё равно осознанный: сообщение указывает на первую реальную
    проблему ввода, а не смешивает, например, "есть буква" и "неверная
    длина" в одном тексте.

    Никогда не бросает исключение — на любом мусоре из JSON-тела запроса
    (число, список, словарь, юникод-цифры) возвращает текст ошибки, а не
    падает (см. test_does_not_raise_on_arbitrary_garbage).
    """
    text = normalize_inn(value)
    if not text:
        return ERROR_BLANK
    if not _is_ascii_digits(text):
        return ERROR_NOT_DIGITS
    if len(text) not in INN_LENGTHS:
        return ERROR_LENGTH
    return None


def is_valid_inn(value: Any) -> bool:
    return validate_inn(value) is None
