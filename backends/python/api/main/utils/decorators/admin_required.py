"""Серверная проверка роли администратора — точечное исключение.

ВАЖНО ПРО ИСТОРИЮ, иначе это выглядит как регресс. В спринте 1 админские
операции и денежные отчёты были закрыты декоратором @admin_required.
11.06.2026 владелец продукта это решение ОТМЕНИЛ: серверного гейта по роли в
приложении нет, любой аутентифицированный пользователь может звать любой
эндпоинт, а флаг is_b24_user_admin остался только фронту — прятать экран
настроек. На это есть отдельный набор тестов (tests_security_roles).

31.08.2026 заказчик вернул проверку ТОЧЕЧНО — только для закрытия и
переоткрытия месяца. Обоснование: это операции другого класса, чем просмотр
отчёта. Закрытие необратимо замораживает часы, которые уходят клиенту в счёт;
переоткрытие задним числом меняет цифры, уже легшие в основу акта. Ошибка
здесь стоит дороже, чем неудобство лишней проверки.

Общее решение от 11.06.2026 при этом НЕ отменено: на все остальные эндпоинты
декоратор не вешается, и tests_security_roles продолжают его закреплять.

Применять ПОСЛЕ @auth_required — нужен request.bitrix24_account.
"""

from functools import wraps

from django.http import JsonResponse


def admin_required(view_func):
    @wraps(view_func)
    def wrapped(request, *args, **kwargs):
        account = getattr(request, "bitrix24_account", None)
        if account is None or not getattr(account, "is_b24_user_admin", False):
            return JsonResponse(
                {
                    "error": "Закрывать и переоткрывать периоды может только администратор.",
                    "code": "admin_required",
                },
                status=403,
            )
        return view_func(request, *args, **kwargs)

    return wrapped
