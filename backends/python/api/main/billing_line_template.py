"""Варианты наполнения счёта и формулировка строки.

Зачем. Строка счёта раньше называлась ровно так, как названа карточка
проекта. У НУОЛАБ карточка названа по клиенту, и в счёт ушло «НУОЛАБ» —
описания работ в документе не оказалось вовсе. Название работ должно приходить
из задач, а как именно оно читается — решает портал, а не код: у одних в
строке «Настройка отчётов, август 2026», у других «Настройка отчётов
(Проект X)». Поэтому формулировка вынесена в настройку приложения
(``billing_line_template``), а не зашита в сервис.

ЧЕТЫРЕ ВАРИАНТА наполнения, и у каждого своя формулировка. Один общий
шаблон на все четыре не годится: «{задача}, {месяц}» в счёте на одну строку
читается как «Услуги по договору, август 2026» — то есть ни о чём, а «Работы
{сотрудник}» в строке на задачу оставило бы строку без описания работ.
Поэтому шаблон у каждого варианта свой ключ настройки, а не один общий:

``task``       «{задача}, {месяц}» — «Настройка отчётов, август 2026»;
``project``    «{услуга} по проекту „{проект}“, {месяц}»;
``employee``   «Работы {сотрудник}, {месяц}»;
``single``     «Услуги по разработке и сопровождению за {месяц}».

Какой вариант мастер подставляет при открытии — настройка портала
``billing_line_variant``. Раньше «по задачам» было зашито в код, и портал,
который выставляет одной строкой, каждый раз переключал вариант руками.

Подстановки — семь, по-русски:

``{задача}``   предмет строки. При варианте «по задачам» это название задачи;
               при остальных — предмет соответствующего варианта (проект,
               сотрудник, «Услуги по договору»). Слот один и тот же: «то, о чём
               эта строка».
``{проект}``   название проекта строки. Пусто, когда строка собрала часы
               НЕСКОЛЬКИХ проектов (одной строкой, по сотрудникам): назвать
               один из них значило бы соврать в печатной форме.
``{сотрудник}`` фамилия и имя, когда часы строки списал ОДИН человек. Пусто,
               когда их несколько, — по той же причине.
``{услуга}``   текст услуги из настройки ``billing_service_name``
               («Разработка»): то, что подставляется в «{услуга} по проекту».
``{клиент}``   название клиента документа.
``{месяц}``    «август 2026» либо «август—сентябрь 2026» для периода из
               нескольких месяцев.
``{период}``   «01.08.2026—31.08.2026».

Три правила подстановки, и все три — про то, чтобы молча не испортить текст
документа.

1. НЕИЗВЕСТНАЯ подстановка остаётся в тексте как есть: ``{задание}`` так и
   уйдёт в предпросмотр строкой ``{задание}``. Стереть её значило бы отдать
   человеку правильно выглядящую строку с пропавшим куском формулировки —
   опечатку в настройке никто бы не заметил до разговора с клиентом. А
   видимая фигурная скобка в предпросмотре ловится глазом сразу.
2. ИЗВЕСТНАЯ подстановка без значения (у документа нет клиента, у строки нет
   проекта) убирается вместе с прилипшим к ней разделителем: «Задача, » и
   «Задача ()» в счёте выглядят как потерянные данные. Подставлять сюда
   «понятный текст» вроде «клиент не указан» нельзя — это печатная форма для
   клиента, и служебная пометка в наименовании работ хуже её отсутствия.
3. Если после подстановок не осталось ничего — возвращается предмет строки.
   Пустое наименование работ не имеет права уйти в счёт ни при какой настройке.
"""

import re
from datetime import date
from typing import Any, Dict, Mapping, Optional

# Варианты наполнения счёта. Они же значения поля ``grouping`` фильтра:
# вариант и есть признак, по которому собираются строки, и держать два
# словаря с одними и теми же четырьмя словами значило бы однажды их
# разойтись. billing_service.GROUPINGS — это тот же кортеж.
LINE_VARIANT_TASK = "task"
LINE_VARIANT_PROJECT = "project"
LINE_VARIANT_EMPLOYEE = "employee"
LINE_VARIANT_SINGLE = "single"
LINE_VARIANTS = (
    LINE_VARIANT_TASK,
    LINE_VARIANT_PROJECT,
    LINE_VARIANT_EMPLOYEE,
    LINE_VARIANT_SINGLE,
)

# Вариант по умолчанию, когда настройки портала нет: «по задачам». Название
# задачи — единственное описание работ, которое в приложении есть, и именно
# его отсутствие было исходной жалобой (в счёт клиенту НУОЛАБ ушло имя
# карточки проекта, названной по клиенту).
DEFAULT_LINE_VARIANT = LINE_VARIANT_TASK

# Значение по умолчанию для варианта «по задачам»: «<Название задачи>, август
# 2026». Имя без суффикса оставлено прежним намеренно — под этим ключом
# (``billing_line_template``) формулировка уже лежит в конфигурации порталов,
# и переименование ключа стёрло бы настроенный текст.
DEFAULT_LINE_TEMPLATE = "{задача}, {месяц}"

# Формулировки по умолчанию у остальных вариантов. Каждая написана так, чтобы
# строка читалась в печатной форме без правки: «Разработка по проекту
# „Личный кабинет“, август 2026», «Работы Иванова Петра, август 2026»,
# «Услуги по разработке и сопровождению за август 2026».
DEFAULT_LINE_TEMPLATES = {
    LINE_VARIANT_TASK: DEFAULT_LINE_TEMPLATE,
    LINE_VARIANT_PROJECT: "{услуга} по проекту „{проект}“, {месяц}",
    LINE_VARIANT_EMPLOYEE: "Работы {сотрудник}, {месяц}",
    LINE_VARIANT_SINGLE: "Услуги по разработке и сопровождению за {месяц}",
}

# Ключи настроек с формулировками — по одному на вариант. Плоские ключи, а не
# один словарь: конфигурация приложения хранит скаляры, и словарь в ней
# пришлось бы сериализовать руками.
LINE_TEMPLATE_SETTING_KEYS = {
    LINE_VARIANT_TASK: "billing_line_template",
    LINE_VARIANT_PROJECT: "billing_line_template_project",
    LINE_VARIANT_EMPLOYEE: "billing_line_template_employee",
    LINE_VARIANT_SINGLE: "billing_line_template_single",
}

# Текст услуги для подстановки ``{услуга}`` (настройка
# ``billing_service_name``). Отдельная настройка, а не слово внутри шаблона,
# потому что услуга в формулировке повторяется: «Разработка по проекту…» и
# «Услуги по разработке…» — один и тот же предмет договора, и менять его
# правкой четырёх шаблонов человек забудет.
DEFAULT_SERVICE_NAME = "Разработка"

# Поддерживаемые подстановки. Порядок — для подсказки в интерфейсе.
LINE_TEMPLATE_PLACEHOLDERS = (
    "задача", "проект", "сотрудник", "услуга", "клиент", "месяц", "период",
)

# Уровень задачи в строке (настройка ``billing_line_task_level``): какое
# именно название задачи попадает в ``{задача}``.
#
# «task» — сама задача, в которой отражены часы (лист дерева). «root» — её
# родитель ВЕРХНЕГО уровня: подзадачи схлопываются в одну строку.
#
# Константы живут здесь, а не в billing_service, чтобы их видели оба
# импортёра — и сервис, и разбор настроек (billing_settings): этот модуль
# ничего из main не импортирует и поэтому не может замкнуть импорты.
TASK_LEVEL_TASK = "task"
TASK_LEVEL_ROOT = "root"
TASK_LEVELS = (TASK_LEVEL_TASK, TASK_LEVEL_ROOT)
DEFAULT_TASK_LEVEL = TASK_LEVEL_TASK

MONTHS_NOMINATIVE = (
    "январь", "февраль", "март", "апрель", "май", "июнь",
    "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь",
)

# Маркер пустого значения известной подстановки. \x00 в тексте настройки
# встретиться не может, поэтому он безопасен как временная метка.
_EMPTY = "\x00"

_PLACEHOLDER_RE = re.compile(r"\{([^{}]*)\}")

# Разделители, которые убираются вместе с опустевшей подстановкой. Символы
# перечислены обычной строкой (её же берёт strip), а класс регулярки собирается
# из неё через re.escape — иначе экранирующая обратная косая попала бы в набор
# символов для strip и обрезала бы текст по ней.
_SEPARATOR_CHARS = ",;:·|/-–—"
_SEPARATOR_CLASS = "[" + re.escape(_SEPARATOR_CHARS) + "]"
_BEFORE_EMPTY_RE = re.compile(r"[ \t]*" + _SEPARATOR_CLASS + r"[ \t]*" + _EMPTY)
_AFTER_EMPTY_RE = re.compile(_EMPTY + r"[ \t]*" + _SEPARATOR_CLASS + r"[ \t]*")
# Опустевшая подстановка внутри скобок: «Задача ()» — след пропавшего значения.
_EMPTY_BRACKETS_RE = re.compile(r"[ \t]*\([ \t]*" + _EMPTY + r"[ \t]*\)")


def _text(value: Any) -> str:
    if value is None:
        return ""
    return str(value).strip()


def month_label(period_from: Optional[date], period_to: Optional[date]) -> str:
    """Подстановка ``{месяц}``: «август 2026», «август—сентябрь 2026».

    Годы указываются оба, когда период их пересекает («декабрь 2026 — январь
    2027»): «декабрь—январь 2027» соврал бы про год начала работ.
    """
    if period_from is None and period_to is None:
        return ""
    start = period_from or period_to
    end = period_to or period_from
    if start is None or end is None:
        return ""
    if start > end:
        start, end = end, start

    start_name = MONTHS_NOMINATIVE[start.month - 1]
    end_name = MONTHS_NOMINATIVE[end.month - 1]

    if start.year == end.year:
        if start.month == end.month:
            return f"{start_name} {start.year}"
        return f"{start_name}—{end_name} {start.year}"
    return f"{start_name} {start.year} — {end_name} {end.year}"


def period_label(period_from: Optional[date], period_to: Optional[date]) -> str:
    """Подстановка ``{период}``: «01.08.2026—31.08.2026»."""
    start = period_from.strftime("%d.%m.%Y") if period_from else ""
    end = period_to.strftime("%d.%m.%Y") if period_to else ""
    if start and end:
        return start if start == end else f"{start}—{end}"
    return start or end


def normalize_line_variant(value: Any) -> str:
    """Вариант наполнения из настройки. Чужое значение — «по задачам».

    Опечатка в настройке не имеет права превратить счёт в одну строку
    «Услуги по договору»: это документ, по которому клиент платит, и потеря
    описания работ в нём заметна позже всего.
    """
    text = _text(value).lower()
    return text if text in LINE_VARIANTS else DEFAULT_LINE_VARIANT


def default_line_template(variant: Any = DEFAULT_LINE_VARIANT) -> str:
    """Формулировка по умолчанию для варианта."""
    return DEFAULT_LINE_TEMPLATES[normalize_line_variant(variant)]


def normalize_line_template(value: Any, variant: Any = DEFAULT_LINE_VARIANT) -> str:
    """Шаблон из настройки. Пусто — значение по умолчанию ЭТОГО варианта.

    Пустой шаблон дал бы пустое наименование работ в каждой строке счёта,
    поэтому «ничего не задано» читается как «как по умолчанию», а не как
    «оставить строки без названия». Значение по умолчанию у каждого варианта
    своё: «{задача}, {месяц}» в счёте на одну строку дало бы «Услуги по
    договору, август 2026».
    """
    text = _text(value)
    return text or default_line_template(variant)


def normalize_service_name(value: Any) -> str:
    """Текст услуги для ``{услуга}``. Пусто — «Разработка».

    Пустая услуга оставила бы строку «по проекту „Личный кабинет“» без
    подлежащего — в печатной форме это выглядит как обрезанный текст.
    """
    return _text(value) or DEFAULT_SERVICE_NAME


def render_line_template(
    template: Any,
    values: Mapping[str, Any],
    *,
    fallback: str = "",
    variant: Any = DEFAULT_LINE_VARIANT,
) -> str:
    """Текст строки по шаблону. Правила — в докстринге модуля.

    ``variant`` нужен ровно для одного: пустой шаблон читается как значение
    по умолчанию ЭТОГО варианта, а не варианта «по задачам».

    Все семь известных подстановок присутствуют в ``resolved`` всегда, даже
    если вызывающий их не передал: иначе не переданная ``{сотрудник}``
    считалась бы НЕИЗВЕСТНОЙ и ушла бы в счёт фигурными скобками — ровно то,
    от чего защищает правило 1, вывернутое наизнанку.
    """
    resolved: Dict[str, str] = {name: "" for name in LINE_TEMPLATE_PLACEHOLDERS}
    resolved.update({
        str(key).strip().lower(): _text(value)
        for key, value in (values or {}).items()
    })

    def substitute(match: "re.Match[str]") -> str:
        name = match.group(1).strip().lower()
        if name not in resolved:
            # Неизвестная подстановка остаётся видимой — см. правило 1.
            return match.group(0)
        return resolved[name] or _EMPTY

    text = _PLACEHOLDER_RE.sub(substitute, normalize_line_template(template, variant))

    if _EMPTY in text:
        text = _EMPTY_BRACKETS_RE.sub("", text)
        text = _BEFORE_EMPTY_RE.sub("", text)
        text = _AFTER_EMPTY_RE.sub("", text)
        text = text.replace(_EMPTY, "")

    text = re.sub(r"[ \t]{2,}", " ", text).strip()
    text = text.strip(" \t" + _SEPARATOR_CHARS)

    return text or _text(fallback)
