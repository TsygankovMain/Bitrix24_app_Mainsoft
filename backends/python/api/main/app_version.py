"""Версия собранного фронта — чтобы старая вкладка не обходила серверные правила.

Инцидент 31.08.2026, найден при выкатке переноса списания на бэкенд. После
подмены контейнера пользователь с уже открытым приложением продолжал работать
на СТАРОМ коде: приложение живёт в айфрейме внутри страницы Битрикса, и
привычная жёсткая перезагрузка внешней страницы содержимое фрейма не
обновляет — браузер берёт его из кэша. В логах это выглядело так: у одного
сотрудника записи шли через новую ручку и отвечали 200, а у другого в те же
минуты уходили мимо бэкенда напрямую в Битрикс. Помогла только перезагрузка
самого фрейма.

Тогда это было безобидно: старый путь просто писал в Битрикс как раньше. Но
следующим шагом идёт закрытие месяца, и там та же ситуация означала бы
ДЫРУ В ЗАЩИТЕ: человек со старой вкладкой списал бы часы в закрытый месяц,
обойдя проверку и не подозревая об этом. Поэтому версия проверяется на
сервере, а не только показывается в интерфейсе.

Как считается. Хэш содержимого собранного index.html. Он ссылается на чанки с
хэшами в именах, поэтому меняется при каждой пересборке фронта и не меняется
при рестарте контейнера с тем же образом. Ни build-arg, ни переменных
окружения не нужно — версия выводится из того, что реально отдаётся
браузеру.

Считается один раз и кэшируется в памяти процесса: файл внутри образа
неизменен, а вызывается это на каждой записи часов.
"""

import hashlib
import logging
import threading
from pathlib import Path

from django.conf import settings

logger = logging.getLogger(__name__)

UNKNOWN_VERSION = "unknown"

_cache: dict[str, str] = {}
_lock = threading.Lock()


def _index_path() -> Path:
    # Тот же путь, что у views.serve_spa: /app/frontend_build/index.html.
    return settings.BASE_DIR / "frontend_build" / "index.html"


def get_app_version() -> str:
    """Короткий хэш текущей сборки фронта.

    UNKNOWN_VERSION, если файла нет (локальный запуск бэкенда без собранного
    фронта, dev-контур). В этом случае проверка версии на записи не
    применяется — см. is_version_acceptable.
    """
    cached = _cache.get("version")
    if cached:
        return cached

    with _lock:
        cached = _cache.get("version")
        if cached:
            return cached

        try:
            content = _index_path().read_bytes()
        except OSError as exc:
            # Не ошибка: так выглядит бэкенд, запущенный без сборки фронта.
            logger.info("App version: frontend build not found (%s); version=unknown", exc)
            _cache["version"] = UNKNOWN_VERSION
            return UNKNOWN_VERSION

        version = hashlib.sha256(content).hexdigest()[:12]
        _cache["version"] = version
        logger.info("App version resolved: %s", version)
        return version


def is_version_acceptable(client_version: str | None) -> bool:
    """Можно ли принимать запись от клиента с такой версией.

    Пропускаем в двух случаях, оба намеренно:

    * версия сервера неизвестна (фронт не собран) — тогда сравнивать не с чем,
      и ронять запись из-за особенностей окружения нельзя;
    * клиент версию не прислал — это вкладка, открытая ДО появления самой
      проверки. Отвергать её значило бы сломать работу всем, кто не
      перезагрузился в момент этой выкатки, ради защиты, которой в их коде
      ещё нет. Такие вкладки исчезнут естественным образом, а со следующей
      выкатки заголовок будет у всех.

    Отвергаем только явное расхождение: клиент прислал версию, и она не
    совпала с серверной. Это ровно случай устаревшей вкладки.
    """
    server_version = get_app_version()
    if server_version == UNKNOWN_VERSION:
        return True
    if not client_version:
        return True
    return str(client_version).strip() == server_version
